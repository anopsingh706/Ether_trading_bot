// deploy/make-server-env.js
// ─────────────────────────────────────────────────────────────────────────────
// Builds a MINIMAL .env for the server from your local .env: keeps only the
// variables the bot code actually reads (found by scanning bot/ for process.env.X)
// and drops everything else — old-platform secrets (exchange API keys, 0x key,
// spare RPC URLs…) never reach the server, so a server compromise can't leak them.
//
//   node deploy/make-server-env.js            → writes .env.server (git-ignored)
//
// Prints only variable NAMES, never values. Copy the result to the server with scp
// (see docs/DEPLOY.md), then delete it locally.
// ─────────────────────────────────────────────────────────────────────────────
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC_ENV = path.join(ROOT, '.env');
const OUT_ENV = path.join(ROOT, '.env.server');

// 1) every env var the bot can read
const files = ['botRunner.js', 'botSimRunner.js'];
for (const dir of ['bot', 'bot/models']) {
  for (const f of fs.readdirSync(path.join(ROOT, dir))) {
    if (f.endsWith('.js') && !f.startsWith('backtest')) files.push(path.join(dir, f));
  }
}
const used = new Set();
for (const f of files) {
  const src = fs.readFileSync(path.join(ROOT, f), 'utf8');
  for (const m of src.matchAll(/process\.env\.([A-Z0-9_]+)/g)) used.add(m[1]);
}
// the sim-only / backtest-only knobs are harmless but pointless on a live server
for (const k of [...used]) if (/^(BOT_SIM|BT_|SCAN_|BOT_LEAD_)/.test(k)) used.delete(k);

// 2) filter the local .env line by line
if (!fs.existsSync(SRC_ENV)) { console.error('No .env found next to package.json'); process.exit(1); }
const srcLines = fs.readFileSync(SRC_ENV, 'utf8').split(/\r?\n/);
const chainLine = srcLines.find((l) => /^\s*BOT_CHAIN\s*=/.test(l)) || 'BOT_CHAIN=polygon';
const chain = chainLine.split('=')[1].split('#')[0].trim().toLowerCase() || 'polygon';
// settings that belong only to the OTHER chain are dropped too (e.g. the Polygon RPC key on a Base server)
const OTHER_CHAIN = {
  base:    ['POLYGON_RPC_URL', 'POLYGON_WSS_URL', 'WETH_TOKEN_ADDRESS', 'USDT_TOKEN_ADDRESS', 'BOT_POOL_FEE', 'BOT_POL_PRICE_USD', 'UNISWAP_V3_FACTORY', 'UNISWAP_ROUTER', 'UNISWAP_QUOTER'],
  polygon: ['BASE_RPC_URL', 'BASE_WSS_URL', 'BOT_BASE_POOL_FEE'],
}[chain] || [];
for (const k of OTHER_CHAIN) used.delete(k);
const kept = [], dropped = [];
const out = ['# .env.server — generated by deploy/make-server-env.js on ' + new Date().toISOString().slice(0, 10),
             '# Only the variables the bot reads. Keep this file chmod 600 on the server.', ''];
for (const line of srcLines) {
  const m = line.match(/^\s*([A-Z0-9_]+)\s*=/);
  if (!m) continue;                       // drop comment-only / blank lines (they may mention old values)
  if (used.has(m[1])) { out.push(line.trimEnd()); kept.push(m[1]); }
  else dropped.push(m[1]);
}

// 3) refuse to write a file the bot can't run with
const need = ['PRIVATE_KEY', 'ADMIN_WALLET_ADDRESS'];
if (!kept.includes('DB_URL') && !kept.includes('BOT_DB_URL')) need.push('DB_URL or BOT_DB_URL');
if (chain === 'base' && !kept.includes('BASE_RPC_URL')) console.warn('⚠️  BOT_CHAIN=base but no BASE_RPC_URL — the bot will use the public https://mainnet.base.org');
const missing = need.filter((k) => !k.includes(' or ') && !kept.includes(k)).concat(need.filter((k) => k.includes(' or ')));
if (missing.length) { console.error('Missing required variables: ' + missing.join(', ')); process.exit(1); }

fs.writeFileSync(OUT_ENV, out.join('\n') + '\n', { mode: 0o600 });
console.log(`✅ wrote ${path.relative(process.cwd(), OUT_ENV)} — chain=${chain}`);
console.log(`   kept ${kept.length}: ${kept.join(' ')}`);
console.log(`   dropped ${dropped.length} (not used by the bot): ${dropped.join(' ')}`);
